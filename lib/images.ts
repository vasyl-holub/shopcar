/**
 * Чи це зображення з бекенда, а не з нашої теки public.
 *
 * Оптимізатор Vercel забирає віддалену картинку сам, зі свого сервера —
 * і Cloudflare перед бекендом відповідає йому перевіркою замість файлу,
 * тому замість фото приходить 502. Такі зображення віддаємо браузеру
 * напряму: він іде з адреси користувача, і його не блокують.
 *
 * Локальні файли оптимізацію зберігають.
 */
export function isRemoteImage(src: string) {
  return /^https?:\/\//i.test(src);
}

/**
 * Фото товарів бекенд віддає з адресою піддомену адмінки
 * (manage.shopcar.ua/media/…), але частина файлів лежить лише на публічному
 * домені: на manage вони дають 404, а на shopcar.ua відкриваються. Тому всі
 * зображення з /media беремо з публічного домену.
 */
export function publicImage(src: string) {
  return src.replace(
    /^https?:\/\/manage\.shopcar\.ua\/media\//i,
    "https://shopcar.ua/media/",
  );
}
